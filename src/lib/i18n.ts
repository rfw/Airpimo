const translatedCatalogs: Record<Exclude<Language, "zh-CN">, Record<string, string>> = {
  en: english,
  "zh-TW": locale_zh_TW,
  "ja-JP": locale_ja_JP,
  "ko-KR": locale_ko_KR,
};

/** Translate display text only. Leave unexpected technical diagnostics intact. */
export function translate(text: string, language: Language): string {
  if (language === 'zh-CN') return text;
  const dictionary = translatedCatalogs[language];
  if (Object.prototype.hasOwnProperty.call(dictionary, text)) return dictionary[text];
  const fallback = (key: string) => dictionary[key] ?? english[key] ?? key;
  const http = /^更新服务请求失败（HTTP (\d+)）。$/.exec(text);
  if (http) return `${fallback('更新服务请求失败')} (HTTP ${http[1]}).`;
  const exited = /^UxPlay 意外退出（退出码 (.+)）$/.exec(text);
  if (exited) return `${fallback('UxPlay 意外退出')} (${fallback('退出码')} ${exited[1]})`;
  const launch = /^UxPlay 无法启动：(.+)$/.exec(text);
  if (launch) return `${fallback('UxPlay 无法启动')}: ${translate(launch[1], language)}`;
  const job = /^Windows 无法托管 UxPlay 进程树：(.+)$/.exec(text);
  if (job) return `${fallback('Windows 无法托管 UxPlay 进程树')}: ${job[1]}`;
  const prefixed = /^(.+?)(：|: )(.+)$/.exec(text);
  if (prefixed && Object.prototype.hasOwnProperty.call(english, prefixed[1])) {
    return `${fallback(prefixed[1])}: ${prefixed[3]}`;
  }
  return text;
}

export function translateTemplate(text: string, language: Language, values: Record<string, string | number> = {}): string {
  return translate(text, language).replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
